# Paper integration: everything the analysis writes for the LaTeX sources --------------
#
# Every table and its supplement is written as a complete tabular
# environment to generated/<name>.tex, with the column specification and header
# rows of the original sources (paper_tables.R). Every number quoted in the text is
# recorded with res_put() and written as \resdef{key}{value} to
# generated/results_<script>.tex; supplement/S99_assemble.R concatenates these
# files into generated/results.tex, which both LaTeX files input. Figures are
# written to generated/<name>.pdf.

if (!exists("%||%")) `%||%` <- function(x, y) if (is.null(x)) y else x
source(file.path(BO_ROOT, "R", "paper_tables.R"))
gen_dir <- Sys.getenv("BO_OUT", file.path(dirname(normalizePath(BO_ROOT)), "generated"))   # LaTeX outputs
dir.create(gen_dir, showWarnings = FALSE, recursive = TRUE)

# Number formatting for LaTeX ------------------------------------------------------------
fx <- function(x, d) ifelse(is.na(x), "--", formatC(round(x, d), digits = d, format = "f"))
fsign <- function(x, d) ifelse(is.na(x), "--", sprintf(paste0("%+.", d, "f"), round(x, d)))
fint <- function(x) ifelse(is.na(x), "--", formatC(round(x), format = "d", big.mark = "{,}"))
fpct <- function(p, d = 1) fx(100 * p, d)
fe <- function(x, d = 2) ifelse(is.na(x), "--", sprintf(paste0("%.", d, "e"), x))   # 1.12e-01
fsci <- function(x, d = 1) {                       # \ensuremath{1.2\times10^{3}} (text or math mode)
  if (is.na(x)) return("--")
  if (x == 0) return("0")
  e <- floor(log10(abs(x)))
  m <- x / 10^e
  if (round(m, d) >= 10) { m <- m / 10; e <- e + 1 }
  sprintf("\\ensuremath{%s\\times10^{%d}}", formatC(m, digits = d, format = "f"), e)
}
fsig <- function(x, d = 2) ifelse(is.na(x), "--", formatC(signif(x, d), format = "fg", digits = d))
fvse <- function(x, se, d) ifelse(is.na(x), "--", sprintf("%s (%s)", fx(x, d), fx(se, d)))
fsvse <- function(x, se, d) ifelse(is.na(x), "--", sprintf("$%s$ (%s)", fsign(x, d), fx(se, d)))
frange <- function(x, d) {
  if (all(is.na(x))) return("--")
  lo <- fx(min(x, na.rm = TRUE), d); hi <- fx(max(x, na.rm = TRUE), d)
  if (lo == hi) lo else sprintf("%s--%s", lo, hi)
}

# Result macros ------------------------------------------------------------------------------
.res <- new.env(parent = emptyenv())
res_put <- function(key, value) {
  if (length(value) != 1L || is.na(value)) value <- "--"
  assign(key, as.character(value), envir = .res)
  invisible(value)
}
res_write <- function(script) {
  keys <- sort(ls(.res))
  lines <- c(sprintf("%% generated by analysis/%s -- do not edit", script),
             sprintf("\\resdef{%s}{%s}", keys, vapply(keys, function(k) base::get(k, envir = .res), "")))
  f <- file.path(gen_dir, paste0("results_", sub("[.]R$", "", basename(script)), ".tex"))
  writeLines(lines, f)
  msg("wrote", length(keys), "result macros to", file.path(basename(gen_dir), basename(f)))
  if (exists("write_reps_log")) write_reps_log(script)
}

# Tables -------------------------------------------------------------------------------------
# cells: character matrix or data frame of formatted LaTeX cells, one row per table row;
# groups: rows after which a \midrule is inserted; extra: raw lines before \bottomrule.
emit_table <- function(name, cells, groups = NULL, extra = NULL, spec = NULL, header = NULL) {
  tp <- paper_tables[[name]]
  spec <- spec %||% tp$spec
  header <- header %||% tp$header
  cells <- as.matrix(cells)
  rows <- apply(cells, 1, function(r) paste0(paste(r, collapse = " & "), "\\\\"))
  body <- character(0)
  for (i in seq_along(rows)) {
    body <- c(body, rows[i])
    if (i %in% groups && i < length(rows)) body <- c(body, "\\midrule")
  }
  lines <- c(sprintf("%% generated by the bridgeoverlap analysis -- do not edit"),
             sprintf("\\begin{tabular}{%s}", spec), "\\toprule", header, "\\midrule", body, extra,
             "\\bottomrule", "\\end{tabular}")
  writeLines(lines, file.path(gen_dir, paste0(name, ".tex")))
  msg("wrote", file.path(basename(gen_dir), paste0(name, ".tex")))
}
group_ends <- function(g) which(c(g[-1] != g[-length(g)], FALSE))
fig_file <- function(name) file.path(gen_dir, paste0(name, ".pdf"))
